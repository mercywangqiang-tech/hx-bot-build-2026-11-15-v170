def _phrases(locale: str) -> dict[str, str]:
    lang = _LANG[locale]
    works = dict(zip(WORKS, lang["works"], strict=True))
    out: dict[str, str] = {}
    for key, label in works.items():
        out[f"status.agent.hxAuto.switched.{key}"] = lang["switched"].replace("{work}", label)
        out[f"status.agent.hxAuto.kept.{key}"] = lang["kept"].replace("{work}", label)
        out[f"settings.hxAutoModel.work.{key}"] = label
    out["status.agent.hxAuto.switched"] = lang["plain"]
    out["status.agent.hxAuto.suggest"] = lang["suggest"]
    out.update(dict(zip(SETTINGS_ORDER, lang["settings"], strict=True)))
    return out


